"""Write the naga WGSL snapshot corpus into this module as MoonBit source.

naga keeps one case per file: `tests/in/wgsl/<name>.wgsl` in, and
`tests/out/wgsl/wgsl-<name>.wgsl` out, the latter being what naga's own WGSL
writer produced after parsing and validating the former. The replay test reads
the same pairs from MoonBit and compares them byte for byte, so the corpus has to
live in the repository: `moon test` runs on four targets and only one of them can
read a file.

Usage: python scripts/gen_snapshot_corpus.py --naga <path to the naga crate>
"""

import argparse
import os
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "conformance" / "corpus"
CASES_PER_FILE = 12


def escape(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            continue
        else:
            out.append(ch)
    return "".join(out)


def read_cases(naga):
    tests = Path(naga) / "tests"
    cases = []
    for produced in sorted((tests / "out" / "wgsl").glob("wgsl-*.wgsl")):
        name = produced.name[len("wgsl-") : -len(".wgsl")]
        source = tests / "in" / "wgsl" / (name + ".wgsl")
        if not source.is_file():
            continue
        cases.append(
            (
                name,
                source.read_text(encoding="utf-8"),
                produced.read_text(encoding="utf-8"),
            )
        )
    return cases


def write_chunks(cases):
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    (OUT / "moon.pkg").write_text(
        "// The snapshot corpus: naga's WGSL cases, embedded so every target can\n"
        "// replay them. Generated by `scripts/gen_snapshot_corpus.py`.\n"
        "// Copyright 2026 Leo Cheng\n"
        "// SPDX-License-Identifier: Apache-2.0\n",
        encoding="utf-8",
    )
    index = []
    for start in range(0, len(cases), CASES_PER_FILE):
        chunk = cases[start : start + CASES_PER_FILE]
        number = start // CASES_PER_FILE
        lines = [
            "// Copyright 2026 Leo Cheng",
            "// SPDX-License-Identifier: Apache-2.0",
            "",
            "///|",
            "/// Cases {} to {} of the corpus.".format(start, start + len(chunk) - 1),
            "pub fn chunk_{}() -> Array[(String, String, String)] {{".format(number),
            "  [",
        ]
        for name, source, expected in chunk:
            lines.append(
                '    ("{}", "{}", "{}"),'.format(
                    escape(name), escape(source), escape(expected)
                )
            )
        lines.append("  ]")
        lines.append("}")
        lines.append("")
        (OUT / "chunk_{:02d}.mbt".format(number)).write_text(
            "\n".join(lines), encoding="utf-8"
        )
        index.append(number)
    listing = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "///|",
        "/// Every case of the corpus, in the order the files were read.",
        "pub fn cases() -> Array[(String, String, String)] {",
        "  let all = []",
    ]
    for number in index:
        listing.append("  all.append(chunk_{}())".format(number))
    listing.append("  all")
    listing.append("}")
    listing.append("")
    (OUT / "corpus.mbt").write_text("\n".join(listing), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--naga", required=True, help="path to the naga crate")
    args = parser.parse_args()
    cases = read_cases(args.naga)
    write_chunks(cases)
    print("wrote {} cases".format(len(cases)))


if __name__ == "__main__":
    main()
